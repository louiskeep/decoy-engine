#!/usr/bin/env python3
"""Generate the Faker locale table the provider registry advertises.

A Faker-backed catalogue provider supports a locale when one seeded call
through ``FakerAdapter.generate_batch`` in that locale returns without
raising. Probing through the adapter keeps one definition of "works": the
same method map, default kwargs and date-of-birth anchoring the engine uses.
One seed suffices: probes across many seeds found no seed-dependent result.

Run:  python scripts/gen_faker_locales.py && ruff format src/decoy_engine/providers_v2/_faker_locales.py
Out:  src/decoy_engine/providers_v2/_faker_locales.py  (committed; the guard
      test re-runs ``build_table`` and compares, so a Faker upgrade that
      changes support fails until this is re-run)
"""

from __future__ import annotations

from pathlib import Path

OUT = (
    Path(__file__).resolve().parent.parent
    / "src"
    / "decoy_engine"
    / "providers_v2"
    / "_faker_locales.py"
)

_PROBE_SEED = b"\x00" * 7 + b"\x01"


def build_table() -> tuple[str, tuple[str, ...], dict[str, tuple[str, ...]]]:
    """Return (faker version, all locales, provider -> locales it fails in)."""
    import faker
    from faker.config import AVAILABLE_LOCALES

    from decoy_engine.providers_v2._adapter import ProviderSpec
    from decoy_engine.providers_v2._faker_adapter import _FAKER_METHOD_MAP, FakerAdapter

    adapter = FakerAdapter()
    locales = tuple(sorted(AVAILABLE_LOCALES))
    unsupported: dict[str, tuple[str, ...]] = {}
    for provider in sorted(_FAKER_METHOD_MAP):
        failing = []
        for locale in locales:
            spec = ProviderSpec(
                locale=locale, deterministic=False, namespace=None, seed=_PROBE_SEED
            )
            try:
                adapter.generate_batch(provider, spec=spec, count=1)
            except Exception:  # any failure means "not supported in this locale"
                failing.append(locale)
        if failing:
            unsupported[provider] = tuple(failing)
    return faker.VERSION, locales, unsupported


def render(version: str, locales: tuple[str, ...], unsupported: dict[str, tuple[str, ...]]) -> str:
    lines = [
        '"""Locales each Faker-backed catalogue provider supports (generated).',
        "",
        "GENERATED by scripts/gen_faker_locales.py - DO NOT EDIT BY HAND.",
        "Advertised in the registry's ``supported_locales``; never enforced: Faker",
        "itself decides which locale strings it accepts (it also takes aliases such",
        "as ``pt-BR`` and ``it``), and the adapter codes its refusals.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'FAKER_VERSION = "{version}"',
        "",
        "ALL_LOCALES: tuple[str, ...] = (",
        *(f'    "{loc}",' for loc in locales),
        ")",
        "",
        "UNSUPPORTED: dict[str, frozenset[str]] = {",
    ]
    for provider, failing in unsupported.items():
        lines.append(f'    "{provider}": frozenset(')
        lines.append("        {")
        lines += [f'            "{loc}",' for loc in failing]
        lines.append("        }")
        lines.append("    ),")
    lines += [
        "}",
        "",
        "",
        "def supported_locales(provider: str) -> tuple[str, ...]:",
        '    """The locales ``provider`` works in under ``FAKER_VERSION``, sorted."""',
        "    excluded = UNSUPPORTED.get(provider, frozenset())",
        "    return tuple(loc for loc in ALL_LOCALES if loc not in excluded)",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.write_text(render(*build_table()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
