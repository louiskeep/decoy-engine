"""Production-seam observers for the Phase F F0 invariants (test-side only).

`observe_pool_seam` records what GENERATION's pooled-faker path actually builds and selects with.
Two seams exist since the unified core: `_faker_pool.open_pooled_selector` (the persistent
per-batch selector the streamed/resident core uses) and `_faker_pool._build_and_sample_returning_pool`
(the whole-table form the legacy path still uses for plans with an ineligible column). Both build
through `build_pool_values`. All three are recorded into one log, one `PoolCall` per pooled column. These are the generation seam; the masking resolver
`pool/_identity.py:resolve_faker_pool_identity` is a different contract and is never consulted
by `generate_tables` (mutating it would not move a single generated byte).

Both hooks are installed by rebinding module attributes with pytest's `monkeypatch`, which is how
the production callers look the functions up (`build_and_sample` calls
`_build_and_sample_returning_pool` by module global; that function calls `build_pool_values` the
same way). The wrappers call through, so recorded runs are byte-identical to unobserved ones.
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Any

import numpy as np
import pytest

from decoy_engine.generation import _faker_pool
from tests.parity._f0_canonical import column_digest


@dataclass
class PoolCall:
    """One pooled-column build+selection as the generation seam saw it."""

    faker_type: str
    faker_kwargs: dict[str, Any]
    n: int
    build_seed: bytes
    selection_seed: bytes
    effective_locale: str | None
    pool_size: int
    pool_values: list[Any] | None
    sampled: list[Any] | None
    # "numpy": the whole-table legacy draw (`selection_seed` seeds default_rng). "kernel": the
    # unified core's position-keyed index kernel (`selection_seed` is the 32-byte column key).
    selection: str = "numpy"

    def pool_digest(self) -> str:
        import pyarrow as pa

        assert self.pool_values is not None
        return column_digest(pa.array(self.pool_values))

    def selection_indices(self) -> np.ndarray[Any, Any]:
        """The index stream the recorded selection draws, recomputed without production code.

        NumPy: `default_rng(selection_seed).integers`. Kernel: `derive_index` of the global row
        under the pinned namespace, computed by the determinism primitive itself (the namespace is
        spelled out here on purpose, so renaming it in production trips the seam test).
        """
        if self.selection == "kernel":
            from decoy_engine.determinism import derive_index
            from decoy_engine.kernel import encode_int

            return np.array(
                [
                    derive_index(
                        self.selection_seed,
                        "gen/select/uniform",
                        encode_int(g),
                        pool_size=self.pool_size,
                    )
                    for g in range(self.n)
                ],
                dtype=np.int64,
            )
        rng = np.random.default_rng(int.from_bytes(self.selection_seed, "big"))
        return rng.integers(0, self.pool_size, size=self.n)

    def signature(self) -> dict[str, Any]:
        """The checked-in form (`_f0_expected.POOL_SEAM`)."""
        return {
            "faker_type": self.faker_type,
            "faker_kwargs": self.faker_kwargs,
            "n": self.n,
            "locale": self.effective_locale,
            "pool_size": self.pool_size,
            "build_seed": self.build_seed.hex(),
            "selection": self.selection,
            "selection_seed": self.selection_seed.hex(),
            "pool_digest": self.pool_digest(),
            "sampled_digest": hashlib.sha256(repr(self.sampled).encode()).hexdigest(),
        }


@dataclass
class PoolSeamLog:
    calls: list[PoolCall]
    build_pool_value_calls: int = 0


@contextmanager
def observe_pool_seam(mp: pytest.MonkeyPatch) -> Iterator[PoolSeamLog]:
    """Record every generation pool build+selection while the block runs."""
    log = PoolSeamLog(calls=[])
    real_returning = _faker_pool._build_and_sample_returning_pool
    real_build = _faker_pool.build_pool_values

    def build_spy(*args: Any, **kwargs: Any) -> Any:
        log.build_pool_value_calls += 1
        return real_build(*args, **kwargs)

    def returning_spy(**kwargs: Any) -> Any:
        result = real_returning(**kwargs)
        log.calls.append(
            PoolCall(
                faker_type=kwargs["faker_type"],
                faker_kwargs=dict(kwargs["faker_kwargs"]),
                n=kwargs["n"],
                build_seed=kwargs["build_seed"],
                selection_seed=kwargs["selection_seed"],
                effective_locale=kwargs["effective_locale"],
                pool_size=kwargs["pool_size"],
                pool_values=result[0],
                sampled=result[1],
            )
        )
        return result

    real_open = _faker_pool.open_pooled_selector

    def open_spy(**kwargs: Any) -> Any:
        selector = real_open(**kwargs)
        if selector is None:
            return None
        build_seed = _faker_pool._pool_seeds(kwargs["gen_ctx"])[0]
        call = PoolCall(
            faker_type=kwargs["faker_type"],
            faker_kwargs=dict(kwargs["faker_kwargs"]),
            n=0,
            build_seed=build_seed,
            selection_seed=selector._indexer.key,
            effective_locale=kwargs["effective_locale"],
            pool_size=len(selector._values),
            pool_values=selector._values.tolist(),
            sampled=[],
            selection="kernel",
        )
        log.calls.append(call)
        real_select = selector.select

        def select_spy(offset: int, size: int) -> Any:
            picked = real_select(offset, size)
            call.n += size
            assert call.sampled is not None
            call.sampled.extend(picked)
            return picked

        selector.select = select_spy  # type: ignore[method-assign]
        return selector

    mp.setattr(_faker_pool, "build_pool_values", build_spy)
    mp.setattr(_faker_pool, "_build_and_sample_returning_pool", returning_spy)
    mp.setattr(_faker_pool, "open_pooled_selector", open_spy)
    yield log


def capture_pool_seam(run: Callable[[], Any]) -> PoolSeamLog:
    """Standalone (non-pytest) capture used by the expectation capture script."""
    mp = pytest.MonkeyPatch()
    try:
        with observe_pool_seam(mp) as log:
            run()
    finally:
        mp.undo()
    return log
