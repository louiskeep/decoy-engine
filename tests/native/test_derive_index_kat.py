@_NEEDS_COMPANION
@pytest.mark.parametrize("native_threads", [1, 2, 4, 8], ids=lambda t: f"threads_{t}")
def test_compiled_matches_live_python_over_random_inputs(native_threads: int) -> None:
    """Differential: the compiled derive_index_batch equals the shipped Python derive_index per
    non-null row over varied inputs, at every thread count."""
    import decoy_engine_native._kernel as kernel
    import pyarrow as pa

    seed = bytes(range(32))
    namespace = "pool.city"
    values = [None if i % 6 == 0 else f"user-{i}-{'z' * (i % 4)}" for i in range(500)]
    array = pa.array(values, type=pa.string())
    for pool_size in (1, 2, 97, 100003):
        out = kernel.derive_index_batch(
            array,
            mask_key=seed,
            namespace=namespace,
            pool_size=pool_size,
            native_threads=native_threads,
        ).to_pylist()
        for value, got in zip(values, out, strict=True):
            if value is None:
                assert got is None
                continue
            expected = derive_index(
                seed, namespace, _canonicalize_source(value), pool_size=pool_size
            )
            assert got == expected, f"pool={pool_size} value={value!r}: {got} != {expected}"


@_NEEDS_COMPANION
def test_compiled_non_integer_pool_size_is_ordered_after_canonicalization() -> None:
    """A non-int pool_size raises TypeError, but ONLY in the pool-guard slot: after the Arrow
    import and the first non-null row's canonicalization, and skipped entirely for a batch that
    validates nothing. So it must NOT short-circuit ahead of those, matching the reference (whose
    non-int rejection is the in-`derive_index` `pool_size > _POOL_SIZE_MAX` comparison, fired per
    non-null row after canonicalization, never for an all-null batch)."""
    import decoy_engine_native._kernel as kernel
    import pyarrow as pa

    seed = bytes(range(32))
    not_an_int = "not-an-int"

    # A clean first non-null row -> the non-int is rejected as TypeError (not a coded ValueError).
    clean = pa.array(["alice", "bob"], type=pa.string())
    with pytest.raises(TypeError):
        kernel.derive_index_batch(
            clean, mask_key=seed, namespace="ns", pool_size=not_an_int, native_threads=1
        )

    # A canon fault on the FIRST non-null row outranks the non-int pool: the canonicalization
    # ValueError wins, proving the non-int check did not fire ahead of the import + canon.
    bad_first = pa.array([2**63 - 1, 0], type=pa.timestamp("s", tz="UTC"))
    with pytest.raises(ValueError, match="mixed_object_not_native"):
        kernel.derive_index_batch(
            bad_first, mask_key=seed, namespace="ns", pool_size=not_an_int, native_threads=1
        )

    # All-null and empty batches validate NOTHING, so a non-int pool is tolerated (null/empty out).
    all_null = pa.array([None, None], type=pa.string())
    assert kernel.derive_index_batch(
        all_null, mask_key=seed, namespace="ns", pool_size=not_an_int, native_threads=1
    ).to_pylist() == [None, None]
    empty = pa.array([], type=pa.string())
    assert (
        kernel.derive_index_batch(
            empty, mask_key=seed, namespace="ns", pool_size=not_an_int, native_threads=1
        ).to_pylist()
        == []
    )


@_NEEDS_COMPANION
def test_panic_in_a_derive_index_worker_becomes_coded_error(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A panic inside a Rayon worker on the derive_index parallel fill must propagate out of the
    pool, unwind through the GIL-released region, and surface as the coded internal_panic error, not
    abort. Driven by DECOY_ENGINE_NATIVE_FORCE_PANIC_IN_WORKER (fires only on a pool worker);
    native_threads=2 over a 2-row batch forces two non-empty ranges."""
    import decoy_engine_native._kernel as kernel
    import pyarrow as pa

    values = pa.array(["a", "b"], type=pa.string())
    mask_key = b"\x44" * 32

    monkeypatch.setenv("DECOY_ENGINE_NATIVE_FORCE_PANIC_IN_WORKER", "1")
    with pytest.raises(ValueError, match="internal_panic"):
        kernel.derive_index_batch(
            values, mask_key=mask_key, namespace="pool.city", pool_size=1000, native_threads=2
        )

    # The GIL was restored and the pool is reusable: a clean call succeeds in the same process.
    monkeypatch.delenv("DECOY_ENGINE_NATIVE_FORCE_PANIC_IN_WORKER")
    out = kernel.derive_index_batch(
        values, mask_key=mask_key, namespace="pool.city", pool_size=1000, native_threads=2
    )
    assert len(out) == 2
