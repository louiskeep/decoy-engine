"""Loader for the frozen F33 conformance corpus (`tests/fixtures/signed_evidence/v1`).

The corpus is generated by an implementation independent of the production verifier (see
`generator/gen.mjs`) and is never regenerated from the code under test.
"""

from __future__ import annotations

import base64
import json
import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from decoy_engine.signed_evidence import (
    ExpectedArtifact,
    HistoricalDecision,
    Purpose,
    RequiredCatalog,
    TrustPolicy,
    VerificationContext,
)

CORPUS = Path(__file__).resolve().parents[2] / "fixtures" / "signed_evidence" / "v1"


def manifest() -> dict[str, Any]:
    return json.loads((CORPUS / "MANIFEST.json").read_text(encoding="utf-8"))


def vector_ids() -> list[str]:
    return list(manifest()["vectors"])


def _b64u(s: str) -> bytes:
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


@dataclass(frozen=True)
class Vector:
    id: str
    statement: bytes
    signature: bytes | None
    context: dict[str, Any]
    expected: dict[str, Any]

    @property
    def dir(self) -> Path:
        return CORPUS / "vectors" / self.id


def load(vector_id: str) -> Vector:
    d = CORPUS / "vectors" / vector_id
    sig = d / "signature.json"
    return Vector(
        id=vector_id,
        statement=(d / "statement.bin").read_bytes(),
        signature=sig.read_bytes() if sig.exists() else None,
        context=json.loads((d / "context.json").read_text(encoding="utf-8")),
        expected=json.loads((d / "expected.json").read_text(encoding="utf-8")),
    )


def materialize_artifacts(vec: Vector, dest: Path) -> Path:
    """Copy the shared base artifact set to `dest` and apply the vector's declared ops."""
    shutil.copytree(CORPUS / "artifacts" / vec.context["artifacts_root"], dest)
    for op in vec.context["artifact_ops"]:
        kind = op["op"]
        if kind == "flip_byte":
            p = dest / op["path"]
            data = bytearray(p.read_bytes())
            data[op["offset"]] ^= 0x01
            p.write_bytes(bytes(data))
        elif kind == "delete":
            (dest / op["path"]).unlink()
        elif kind == "delete_all":
            for child in dest.iterdir():
                shutil.rmtree(child) if child.is_dir() else child.unlink()
        elif kind == "add":
            p = dest / op["path"]
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(_b64u(op["content_b64"]))
        elif kind == "rename":
            target = dest / op["to"]
            target.parent.mkdir(parents=True, exist_ok=True)
            (dest / op["from"]).rename(target)
        else:  # pragma: no cover - a corpus bug, not a product path
            raise AssertionError(f"unknown corpus artifact op {kind!r}")
    return dest


def build_context(vec: Vector) -> VerificationContext:
    c = vec.context
    policy = TrustPolicy.from_bytes(
        (CORPUS / c["trust_policy_file"]).read_bytes(), pinned_sha256=c["trust_policy_sha256"]
    )
    catalog = RequiredCatalog.from_bytes((CORPUS / c["catalog_file"]).read_bytes())
    exp = c["expected"]
    return VerificationContext(
        purpose=Purpose[c["purpose"]],
        trust_policy=policy,
        required_catalog=catalog,
        expected_tenant=exp.get("tenant"),
        expected_bundle_id=exp.get("bundle_id"),
        expected_job_id=exp.get("job_id"),
        expected_attempt_id=exp.get("attempt_id"),
        expected_snapshot_id=exp.get("snapshot_id"),
        expected_artifacts=tuple(
            ExpectedArtifact(id=a["id"], sha256=a["sha256"], media_type=a["media_type"])
            for a in exp["artifacts"]
        ),
        historical_decisions=tuple(
            HistoricalDecision(
                statement_sha256=d["statement_sha256"],
                signature_sha256=d["signature_sha256"],
                decision_ref=d["decision_ref"],
                policy_digest=d["policy_digest"],
            )
            for d in c["historical_decisions"]
        ),
        evaluation_time=datetime.fromisoformat(c["evaluation_time"].replace("Z", "+00:00")),
    )
