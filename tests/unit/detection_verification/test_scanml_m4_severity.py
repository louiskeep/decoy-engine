"""AT-M4b and AT-M4f: the model severity table on the real spaCy model and the real classifier pack.

One wide output table holds a column per cell of the table in the plan (Post-scan, severity), each
generated by `_scanml_m4_support.notes_column`: `every=2` names a person in about half the cells
(over `NER_MIN_RATE`), `every=10` in about one in ten (under it), and `redacted=True` names nobody.
The table runs once under `ner_findings: warn` and once under `fail`. A short-value column of
person names is not free text: it gives no NER row and none of its cells reaches spaCy (spy on the
one pipeline load seam, so a scorer that bypasses `ner_rates` is caught too).

Mutations: M-M4b (ignore `ner_findings`), M-M4b2 (route NER findings through `_classify`),
M-M4b3 (score with `iter_ner_spans_batch` directly), M-M4f (classifier findings through
`_escalate`).
"""

from __future__ import annotations

from typing import Any

import pandas as pd
import pytest

from tests._ner import needs_ner
from tests.unit.detection_verification import _scanml_m4_support as s

NER_ON = {"provider_config": {"ner": {"model": "en_core_web_sm"}}}
MANY, FEW = 2, 10


def _columns() -> dict[str, tuple[dict[str, Any] | None, list[str], str | None]]:
    """Column -> (config entry, None when unconfigured; output cells; warn-mode severity or None)."""
    many, few = s.notes_column(MANY), s.notes_column(FEW)
    return {
        "notes_none": (None, many, "warning"),
        "notes_low": (None, few, "info"),
        "notes_pass": ({"strategy": "passthrough"}, many, "info"),
        "notes_tr": ({"strategy": "text_redact"}, many, "warning"),
        "notes_hash": ({"strategy": "hash", "namespace": "h"}, many, "warning"),
        "notes_trn_clean": (
            {"strategy": "text_redact", **NER_ON},
            s.notes_column(MANY, redacted=True),
            None,
        ),
        "notes_trn_few": ({"strategy": "text_redact", **NER_ON}, few, "info"),
        "notes_trn_many": ({"strategy": "text_redact", **NER_ON}, many, "warning"),
        "notes_tm_many": ({"strategy": "text_mask", **NER_ON}, many, "warning"),
        "notes_faker": ({"strategy": "faker", "provider": "lorem_text"}, many, "info"),
        "notes_shuffle": ({"strategy": "shuffle", "namespace": "s"}, many, "info"),
        "names_faker": (
            {"strategy": "faker", "provider": "person_full_name"},
            s.short_names(),
            None,
        ),
        "notes_redact": ({"strategy": "redact"}, ["REDACTED"] * s.CELLS, None),
        "names_short": (None, s.short_names(), None),
        "notes_dismissed": (None, many, "info"),
    }


def _run(mode: str) -> tuple[dict[str, Any], dict[str, Any]]:
    columns = _columns()
    out = pd.DataFrame({name: cells for name, (_, cells, _) in columns.items()})
    out["memo"] = [f"write to user{i}@example.com" for i in range(s.CELLS)]
    entries = [{"name": n, **entry} for n, (entry, _, _) in columns.items() if entry is not None]
    entries.append({"name": "memo", "strategy": "redact"})
    detectors = s.detector_set("ner")
    dismissal = {
        "table": "t",
        "column": "notes_dismissed",
        "detector_id": "person_name",
        "source": "ner",
        "model_id": detectors.ner.id,
        "model_version": detectors.ner.version,
        "strategy": None,
    }
    post_scan = {"detectors": ["regex", "ner"], "ner_findings": mode, "dismissed": [dismissal]}
    cfg = s.config([s.table_config("t", entries)], post_scan=post_scan)
    report = s.run_post_mask({"t": out.copy()}, {"t": out}, cfg, detectors)
    return report, columns


def _person_rows(report: dict[str, Any], column: str) -> list[dict[str, Any]]:
    return s.rows(report, "ner", column=column, detector_id="person_name")


@needs_ner
def test_warn_mode_severity_table(monkeypatch: pytest.MonkeyPatch) -> None:
    spy = s.spy_pipeline(monkeypatch)
    report, columns = _run("warn")
    for column, (_, _, want) in columns.items():
        found = _person_rows(report, column)
        if want is None:
            assert found == [], (column, found)
            continue
        assert len(found) == 1, (column, report["residual_pii"])
        assert found[0]["severity"] == want, (column, found[0])
        assert found[0]["promoted"] is False
    short = set(columns["names_short"][1]) | set(columns["names_faker"][1])
    assert spy.texts, "the spy saw no NER call"
    assert not short & set(spy.texts), "a short-value cell reached the NER pipeline"
    # Location rows only where a location was found; none in these columns.
    assert not s.rows(report, "ner", detector_id="location")


@needs_ner
def test_fail_mode_promotes_only_standing_ner_warnings() -> None:
    report, columns = _run("fail")
    for column, (_, _, want) in columns.items():
        found = _person_rows(report, column)
        if want is None:
            assert found == [], column
            continue
        (finding,) = found
        if want == "warning":
            assert (finding["severity"], finding["promoted"]) == ("fail", True), column
        else:
            assert (finding["severity"], finding["promoted"]) == (want, False), column


@needs_ner
def test_ner_rows_carry_rate_hit_cells_and_the_model_that_ran() -> None:
    from decoy_engine.detection import _ner_rate as nr

    report, columns = _run("warn")
    (row,) = _person_rows(report, "notes_none")
    rate = nr.ner_rates(columns["notes_none"][1])["person_name"]
    assert row["match_rate"] == rate.rate and row["match_rate"] >= nr.NER_MIN_RATE
    assert row["sample_match_count"] == rate.hit_cells
    assert row["model"] == {"id": "en_core_web_sm", "version": "3.8.0"}
    assert row["band"] is None
    (few,) = _person_rows(report, "notes_low")
    assert 0 < few["match_rate"] < nr.NER_MIN_RATE


@needs_ner
def test_a_dismissed_warning_stays_info_under_fail_and_a_regex_fail_is_never_promoted() -> None:
    for mode in ("warn", "fail"):
        report, _ = _run(mode)
        (dismissed,) = _person_rows(report, "notes_dismissed")
        assert (dismissed["severity"], dismissed["dismissed"], dismissed["promoted"]) == (
            "info",
            True,
            False,
        )
        regex_fails = s.rows(report, "regex", severity="fail")
        assert any(f["column"] == "memo" for f in regex_fails), report["residual_pii"]
        assert all(f["promoted"] is False for f in s.rows(report, "regex"))


def _classifier_case(mode: str) -> dict[str, Any]:
    emails = [f"user{i}@example.com" for i in range(60)]
    frame = pd.DataFrame({"email": emails})
    post_scan = {"detectors": ["regex", "classifier", "ner"], "ner_findings": mode}
    cfg = s.config([s.table_config("t", [])], post_scan=post_scan)
    # Output equal to the source on an unconfigured column: the regex path escalates to `fail`.
    return s.run_post_mask({"t": frame.copy()}, {"t": frame}, cfg, s.detector_set("classifier"))


@pytest.mark.parametrize("mode", ["warn", "fail"])
def test_classifier_findings_never_exceed_warning(mode: str) -> None:
    report = _classifier_case(mode)
    (finding,) = s.rows(report, "classifier", column="email")
    assert (finding["severity"], finding["promoted"]) == ("warning", False)
    assert s.rows(report, "regex", column="email", severity="fail"), "the regex path must fail it"
