"""The pinned-generation plan: a fully resolved, serializable, seed-independent job description.

A ``PinnedPlan`` captures every input that determines generated bytes EXCEPT the caller seed:
per-table names, row counts and dependency edges, the ordered column declarations with their
resolved config, the statistical snapshot digests (and the specs built from those exact bytes),
the single ``reference_date`` the only clock-reading site (``windowed_date``) resolves against,
and the runtime identity (library versions) the bytes depend on. ``fingerprint`` hashes that
payload, so any drift in a pinned input changes the fingerprint instead of silently changing
output.

Methodology: canonical JSON hashing in the style of RFC 8785 (JCS) key-sorted, fixed-separator
serialization, hashed with SHA-256 (FIPS 180-4); the same canonical-JSON approach
``generators.derivation.strategy_config_fingerprint`` already uses for per-column seeds.
Content-addressing of external inputs by digest follows the lockfile model (pip/uv hash pinning).
"""

from __future__ import annotations

import hashlib
import json
import platform
from dataclasses import dataclass
from typing import Any

from decoy_engine import reasons
from decoy_engine._reference_date import PinnedModeError

PINNED_PLAN_SCHEMA = "pinned-plan/v1"
_FINGERPRINT_SCHEMA = "pinned-plan-fingerprint/v1"

MAX_SEED = 1 << 64


@dataclass(frozen=True)
class PinnedColumn:
    """One declared column: its name and its resolved config as canonical JSON."""

    name: str
    config_json: str


@dataclass(frozen=True)
class PinnedTable:
    name: str
    row_count: int
    depends_on: tuple[str, ...]
    columns: tuple[PinnedColumn, ...]


@dataclass(frozen=True)
class PinnedStatistical:
    """A statistical column's pinned snapshot digest and the spec built from those bytes."""

    table: str
    column: str
    snapshot_digest: str
    spec_json: str


@dataclass(frozen=True)
class PinnedPlan:
    schema_version: str
    reference_date: str
    runtime_identity: tuple[tuple[str, str], ...]
    tables: tuple[PinnedTable, ...]
    statistical: tuple[PinnedStatistical, ...]
    # ``(table, column, "int64" | "float64")`` for each column the whole-table route would keep
    # numeric, decided once at compile time from the full config (relationships included). Empty
    # means "no numeric columns", and also what a plan written before this field loads as; an
    # empty value is left out of ``to_dict`` and the fingerprint so those plans keep their bytes.
    numeric_types: tuple[tuple[str, str, str], ...] = ()

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "schema_version": self.schema_version,
            "reference_date": self.reference_date,
            "runtime_identity": dict(self.runtime_identity),
            "tables": [
                {
                    "name": t.name,
                    "row_count": t.row_count,
                    "depends_on": list(t.depends_on),
                    "columns": [{"name": c.name, "config_json": c.config_json} for c in t.columns],
                }
                for t in self.tables
            ],
            "statistical": [
                {
                    "table": s.table,
                    "column": s.column,
                    "snapshot_digest": s.snapshot_digest,
                    "spec_json": s.spec_json,
                }
                for s in self.statistical
            ],
        }
        if self.numeric_types:
            out["numeric_types"] = [list(n) for n in self.numeric_types]
        return out

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> PinnedPlan:
        try:
            return cls(
                schema_version=str(data["schema_version"]),
                reference_date=str(data["reference_date"]),
                runtime_identity=tuple(
                    sorted((str(k), str(v)) for k, v in data["runtime_identity"].items())
                ),
                tables=tuple(
                    PinnedTable(
                        name=str(t["name"]),
                        row_count=int(t["row_count"]),
                        depends_on=tuple(str(d) for d in t["depends_on"]),
                        columns=tuple(
                            PinnedColumn(name=str(c["name"]), config_json=str(c["config_json"]))
                            for c in t["columns"]
                        ),
                    )
                    for t in data["tables"]
                ),
                statistical=tuple(
                    PinnedStatistical(
                        table=str(s["table"]),
                        column=str(s["column"]),
                        snapshot_digest=str(s["snapshot_digest"]),
                        spec_json=str(s["spec_json"]),
                    )
                    for s in data["statistical"]
                ),
                numeric_types=_numeric_types(data),
            )
        except (KeyError, TypeError, ValueError, AttributeError) as exc:
            raise PinnedModeError(
                code=reasons.plan.PINNED_PLAN_MALFORMED,
                message=f"serialized pinned plan is malformed ({type(exc).__name__})",
            ) from None


NUMERIC_TYPE_NAMES = frozenset({"int64", "float64"})


def _numeric_types(data: dict[str, Any]) -> tuple[tuple[str, str, str], ...]:
    """Decode the optional field strictly: absent means none; present must be a list of entries."""
    if "numeric_types" not in data:
        return ()
    raw = data["numeric_types"]
    if not isinstance(raw, list):
        raise TypeError("numeric_types is not a list")
    return tuple(_numeric_entry(n) for n in raw)


def _numeric_entry(n: Any) -> tuple[str, str, str]:
    if not isinstance(n, (list, tuple)) or len(n) != 3 or not all(isinstance(v, str) for v in n):
        raise TypeError("numeric_types entry is not three strings")
    table, column, dtype = n
    if dtype not in NUMERIC_TYPE_NAMES:
        raise ValueError("unknown numeric type")
    return (table, column, dtype)


def runtime_identity() -> tuple[tuple[str, str], ...]:
    """The library versions generated bytes depend on, as sorted ``(key, value)`` pairs.

    NumPy is included because null injection, windowed-date sampling and grouped walks draw from
    its generators. The tz policy is fixed UTC: nothing in the pinned path reads local time.
    """
    import numpy
    import pandas
    import pyarrow

    from decoy_engine.determinism import SEED_PROTOCOL_VERSION
    from decoy_engine.release import __version__ as engine_version

    return tuple(
        sorted(
            {
                "engine": str(engine_version),
                "numpy": str(numpy.__version__),
                "pandas": str(pandas.__version__),
                "pyarrow": str(pyarrow.__version__),
                "python": ".".join(platform.python_version_tuple()[:2]),
                "seed_protocol": str(SEED_PROTOCOL_VERSION),
                "tz": "UTC",
            }.items()
        )
    )


def validate_seed(seed: Any) -> int:
    if isinstance(seed, bool) or not isinstance(seed, int) or not 0 <= seed < MAX_SEED:
        raise PinnedModeError(
            code=reasons.plan.PINNED_SEED_INVALID,
            message="seed is required and must be an integer in [0, 2**64)",
        )
    return seed


def _canonical(payload: Any) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")


def fingerprint(plan: PinnedPlan) -> str:
    """SHA-256 hex over the canonical, seed-independent payload of ``plan``.

    The spec JSON enters through its own digest so a hand-edited spec cannot ride under an
    unchanged snapshot digest. The caller seed and the source config's seed never enter.
    """
    payload = {
        "schema": _FINGERPRINT_SCHEMA,
        "plan_schema": plan.schema_version,
        "reference_date": plan.reference_date,
        "runtime_identity": dict(plan.runtime_identity),
        "tables": [
            {
                "name": t.name,
                "row_count": t.row_count,
                "depends_on": list(t.depends_on),
                "columns": [
                    {"name": c.name, "config": json.loads(c.config_json)} for c in t.columns
                ],
            }
            for t in plan.tables
        ],
        "statistical": [
            {
                "table": s.table,
                "column": s.column,
                "snapshot_digest": s.snapshot_digest,
                "spec_sha256": hashlib.sha256(s.spec_json.encode("utf-8")).hexdigest(),
            }
            for s in plan.statistical
        ],
    }
    if plan.numeric_types:
        payload["numeric_types"] = [list(n) for n in plan.numeric_types]
    return hashlib.sha256(_canonical(payload)).hexdigest()
